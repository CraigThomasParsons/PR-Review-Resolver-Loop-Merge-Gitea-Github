#!/usr/bin/env bash
# install-systemd-units.sh: copy the agent pool's systemd user units into the user unit dir.
#
# Installs, from this checkout's systemd/:
#   agent-pool-prod@.service, agent-pool-prod@.timer      one instance per provider
#   agent-pool-doctor.service, agent-pool-doctor.timer
# with @POOL_ROOT@ replaced by --pool-root, plus one generated drop-in per provider,
# agent-pool-prod@<provider>.timer.d/stagger.conf, putting each provider's hourly tick on its
# own minute:
#   claude :05  codex :15  cursor :25  grok :45  agy :55
# (each plus up to 2 minutes of fixed random delay; clear of pr-merge-tick's :08/:23/:38/:53 and
# pr-pipeline's :37). The doctor runs at :02/:17/:32/:47.
#
# It never runs systemctl and enables or starts nothing: it prints the commands to do that.
# Re-running it is safe: identical files are left alone, changed ones replaced atomically.
#
# Usage:
#   install-systemd-units.sh [--dest DIR] [--pool-root DIR] [--list]
#
#   --dest DIR       where to install (default ${XDG_CONFIG_HOME:-~/.config}/systemd/user)
#   --pool-root DIR  the checkout the units run, holding agent-pool/bin (default
#                    %h/.local/share/agent-pool: a deployed copy, not a development checkout;
#                    systemd expands %h to the home directory)
#   --list           print what would change; write nothing
#
# Exit codes: 0 done, 2 bad arguments, 3 write failure.

set -euo pipefail

here="$(cd -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" && pwd)"
src="$(cd -- "$here/../.." && pwd)/systemd"

dest="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
pool_root="%h/.local/share/agent-pool"
list_only=0

usage() { sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'; }
badarg() { printf 'install-systemd-units.sh: %s\n' "$*" >&2; exit 2; }
fail() { printf 'install-systemd-units.sh: FAILED: %s\n' "$*" >&2; exit 3; }

while (($#)); do
  case "$1" in
    --dest) [ "$#" -ge 2 ] || badarg "--dest needs a directory"; dest="$2"; shift 2 ;;
    --pool-root) [ "$#" -ge 2 ] || badarg "--pool-root needs a directory"; pool_root="$2"; shift 2 ;;
    --list) list_only=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) badarg "unknown argument '$1' (see --help)" ;;
  esac
done

[ -n "$dest" ] || badarg "--dest is empty"
# Only a leading %h may be a systemd specifier, and the rest must survive sed and ExecStart= as is.
[[ "$pool_root" =~ ^(%h)?/[A-Za-z0-9._/+-]*$ ]] \
  || badarg "--pool-root must be an absolute path (or start with %h/) of letters, digits and ._/+- (got '$pool_root')"
pool_root="${pool_root%/}"
[ -n "$pool_root" ] && [ "$pool_root" != "%h" ] || badarg "--pool-root may not be / or %h"

UNITS=(agent-pool-prod@.service agent-pool-prod@.timer agent-pool-doctor.service agent-pool-doctor.timer)
STAGGER=(claude:05 codex:15 cursor:25 grok:45 agy:55)

for unit in "${UNITS[@]}"; do
  [ -f "$src/$unit" ] || fail "missing $src/$unit"
done

check_root="${pool_root/#%h/$HOME}"
for script in prod-common.sh doctor.sh; do
  if [ ! -x "$check_root/agent-pool/bin/$script" ]; then
    printf 'install-systemd-units.sh: warning: %s/agent-pool/bin/%s is not there yet; the units will fail until it is\n' \
      "$check_root" "$script" >&2
  fi
done

changed=0
# install_file <relative path> <content>: write atomically unless it is already identical.
install_file() {
  local rel="$1" content="$2" target="$dest/$1" tmp
  if [ -f "$target" ] && [ ! -L "$target" ] && [ "$(cat -- "$target")" = "$content" ]; then
    printf 'unchanged  %s\n' "$target"
    return 0
  fi
  changed=$((changed + 1))
  if [ "$list_only" = 1 ]; then
    if [ -e "$target" ] || [ -L "$target" ]; then printf 'would update  %s\n' "$target"
    else printf 'would add  %s\n' "$target"; fi
    return 0
  fi
  mkdir -p -- "$(dirname -- "$target")" || fail "cannot create $(dirname -- "$target")"
  tmp="$(mktemp -- "$(dirname -- "$target")/.${rel##*/}.XXXXXX")" || fail "cannot write in $(dirname -- "$target")"
  if ! { printf '%s\n' "$content" > "$tmp" && chmod 644 -- "$tmp" && sync -- "$tmp" && mv -f -- "$tmp" "$target"; }; then
    rm -f -- "$tmp"
    fail "cannot write $target"
  fi
  printf 'installed  %s\n' "$target"
}

for unit in "${UNITS[@]}"; do
  content="$(sed "s|@POOL_ROOT@|$pool_root|g" -- "$src/$unit")"
  install_file "$unit" "$content"
done

for entry in "${STAGGER[@]}"; do
  provider="${entry%%:*}" minute="${entry#*:}"
  install_file "agent-pool-prod@$provider.timer.d/stagger.conf" "$(cat <<EOF
# Generated by agent-pool/bin/install-systemd-units.sh: $provider ticks at :$minute (+ up to 2 min).
[Timer]
OnCalendar=
OnCalendar=*-*-* *:$minute:00
EOF
)"
done

if [ "$list_only" = 1 ]; then
  printf '%d file(s) would change in %s; nothing written\n' "$changed" "$dest"
  exit 0
fi

printf '%d file(s) changed in %s. Nothing is enabled; to turn the pool on:\n' "$changed" "$dest"
printf '  systemctl --user daemon-reload\n'
printf '  systemctl --user enable --now agent-pool-doctor.timer\n'
for entry in "${STAGGER[@]}"; do
  printf '  systemctl --user enable --now agent-pool-prod@%s.timer\n' "${entry%%:*}"
done
